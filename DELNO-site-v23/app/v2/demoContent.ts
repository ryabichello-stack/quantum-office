export type DemoAnswerId = keyof typeof demoAnswers;

export function findDemoAnswer(question: string): { id: DemoAnswerId; text: string } {
  const value = question.toLowerCase();
  let id: DemoAnswerId = "overview";

  if (/тариф|цен|сто|руб|2999|5990/.test(value)) id = "pricing";
  else if (/номер|телефон|звон|манго|мегафон|городск|мобильн/.test(value)) id = "phone";
  else if (/telegram|телеграм|max|макс|мессендж|чат/.test(value)) id = "messengers";
  else if (/баз|знан|услуг|товар|прайс|документ/.test(value)) id = "knowledge";
  else if (/запис|календар|встреч|время/.test(value)) id = "booking";
  else if (/подключ|запуск|начать|настро/.test(value)) id = "onboarding";

  return { id, text: demoAnswers[id] };
}
